export function downloadFullCampaignPackJson(pack: FullCampaignPack) {
  const jsonStr = JSON.stringify(pack, null, 2);
  const slug = (pack.campaign.offer.title || 'campaign').toLowerCase().replace(/[^a-z0-9]/g, '_').slice(0, 30);
  saveBlob(jsonStr, `${slug}_campaign_pack.json`, 'application/json;charset=utf-8');
}

